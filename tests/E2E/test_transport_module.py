    async def api(self,path,body=None,page=None,csrf=True):
        # Browser fetch reaches real Laravel and PostgreSQL; no intercepted responses.
        return await (page or self.page).evaluate("""async ({path,body,csrf}) => {
            const headers={Accept:'application/json'};
            if(body!==null){headers['Content-Type']='application/json';if(csrf)headers['X-XSRF-TOKEN']=decodeURIComponent(document.cookie.split('; ').find(v=>v.startsWith('XSRF-TOKEN='))?.slice(11)??'');}
            const response=await fetch('/api'+path,{method:body===null?'GET':'POST',headers,credentials:'same-origin',...(body===null?{}:{body:JSON.stringify(body)})});
            return {status:response.status,body:await response.json()};
        }""",{'path':path,'body':body,'csrf':csrf})
    async def checked(self,path,body,status=201,page=None):
        result=await self.api(path,body,page)
        self.assertEqual(status,result['status'],result['body'])
        return result['body'].get('data')
