"""Real Chromium -> Vue/Blade -> session/CSRF API -> temporary PostgreSQL 18.
No intercepted API responses. Run bash tests/run-postgres.sh --e2e-transport.
"""
import asyncio
import json
import subprocess
import unittest
from playwright.async_api import async_playwright,expect
import test_document_module as support

class TransportModuleE2E(unittest.IsolatedAsyncioTestCase):
    @classmethod
    def setUpClass(cls): support.DocumentModuleE2E.setUpClass.__func__(cls)
    @classmethod
    def tearDownClass(cls): support.DocumentModuleE2E.tearDownClass.__func__(cls)
    @classmethod
    def command(cls,action,data=None):
        completed=subprocess.run(['php',str(support.ROOT/'tests/E2E/transport-console.php'),action],input=json.dumps(data or {}),text=True,capture_output=True,cwd=support.ROOT,check=True)
        return json.loads(completed.stdout)
    async def asyncSetUp(self):
        asyncio.get_running_loop().slow_callback_duration=2.0
        self.fixture=self.command('fixture')
        self.playwright=await async_playwright().start()
        self.browser=await self.playwright.chromium.launch(executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
        self.context=await self.browser.new_context(viewport={'width':1440,'height':1000})
        await self.context.tracing.start(screenshots=True,snapshots=True)
        self.page=await self.context.new_page();self.errors=[]
        self.page.on('pageerror',lambda e:self.errors.append(str(e)))
        self.page.on('dialog',lambda d:asyncio.create_task(d.accept()))
    async def asyncTearDown(self):
        try:
            await self.page.screenshot(path=str(self.artifacts/(self._testMethodName+'.png')),full_page=True)
            await self.context.tracing.stop(path=str(self.artifacts/(self._testMethodName+'.zip')))
        finally:
            await self.context.close();await self.browser.close();await self.playwright.stop()
            self.proxy.drop_response_path=None
            self.proxy.drop_response_statuses=(201,)
        self.assertEqual([],self.errors)
    async def login(self,role='secretary'):
        await self.page.goto(self.base+'/transporte')
        await self.page.get_by_label('Usuario',exact=True).fill('e2e-'+role)
        await self.page.get_by_label('Contraseña',exact=True).fill(support.PASSWORD)
        await self.page.get_by_role('button',name='Iniciar sesión').click()
        await expect(self.page.get_by_role('heading',name='Panel general')).to_be_visible()
    async def save(self,form,suffix,status=201):
        async with self.page.expect_response(lambda r:r.request.method=='POST' and r.url.endswith(suffix)) as event:
            await form.get_by_role('button',name='Guardar',exact=True).click()
        response=await event.value
        self.assertEqual(status,response.status,await response.text())
        self.assertTrue(response.request.headers.get('x-xsrf-token'))
        await expect(self.page.get_by_text('Operación confirmada y datos actualizados.',exact=True)).to_be_visible()
        return (await response.json())['data']
    async def create(self):
        await self.page.get_by_role('button',name='Solicitudes',exact=True).click()
        await self.page.get_by_role('button',name='Registrar solicitud',exact=True).click()
        form=self.page.get_by_role('form',name='Registrar solicitud')
        for label,key in [('Cliente','customer'),('Producto líquido','product'),('Ruta','route')]: await form.get_by_label(label,exact=True).select_option(self.fixture[key])
        await form.get_by_label('Litros solicitados').fill('100.00')
        request=await self.save(form,'/api/transport/requests')
        row=self.page.get_by_role('row').filter(has_text=request['id'])
        await row.get_by_role('button',name='Crear viaje',exact=True).click()
        trip=await self.save(self.page.get_by_role('form',name='Crear viaje asociado'),'/api/transport/trips')
        await expect(self.page.get_by_role('heading',name='Viaje ·',exact=False)).to_be_visible()
        return trip['id']
    async def assign(self,trip,kind,key):
        await self.page.get_by_role('button',name='Recursos',exact=True).click()
        await self.page.get_by_label('Recurso',exact=True).select_option(kind)
        await self.page.get_by_label('Seleccionar recurso',exact=True).select_option(self.fixture[key])
        await self.page.get_by_role('button',name='Consultar disponibilidad').click()
        await expect(self.page.get_by_text('Recurso disponible al consultar',exact=True)).to_be_visible()
        form=self.page.get_by_role('form',name='Asignar recurso')
        await form.get_by_label('Motivo de la operación').fill('Asignación real de prueba')
        await self.save(form,f'/trips/{trip}/assignments/assign')
