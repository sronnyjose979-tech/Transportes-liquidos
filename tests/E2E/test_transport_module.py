    async def test_real_sessions_conflict_stale_transition_cancel_close_and_manual_release(self):
        await self.login()
        await self.checked('/transport/requests',{},422)
        trip=await self.create()
        second=await self.checked('/transport/trips',{'transport_request_id':(await self.checked(f'/transport/trips/{trip}',None,200))['transport_request_id']})
        context=await self.browser.new_context()
        try:
            page=await context.new_page();await page.goto(self.base+'/transporte')
            await page.evaluate("fetch('/api/csrf',{credentials:'same-origin'})")
            await self.checked('/login',{'login':'e2e-secretary','password':support.PASSWORD},200,page)
            payload={'resource_kind':'driver','resource_id':self.fixture['driver'],'reason':'Operación concurrente'}
            results=await asyncio.gather(self.api(f'/transport/trips/{trip}/assignments/assign',payload),self.api(f"/transport/trips/{second['id']}/assignments/assign",payload,page))
            self.assertEqual([201,409],sorted(r['status'] for r in results))
            winner=trip if results[0]['status']==201 else second['id']
            await self.checked(f'/transport/trips/{winner}/start',{'version':1,'reason':'Sin activos'},422)
            await self.checked(f'/transport/trips/{winner}/finish',{'version':1,'reason':'Sin D02'},422)
            result=await self.context.request.post(self.base+f'/api/transport/trips/{winner}/cancel',headers={'Accept':'application/json'},data={'version':1,'reason':'Sin token ni metadatos de origen'})
            self.assertEqual(419,result.status)
            cancelled=await self.checked(f'/transport/trips/{winner}/cancel',{'version':1,'reason':'Cancelación real'},200)
            await self.checked(f'/transport/trips/{winner}/cancel',{'version':1,'reason':'Sesión desactualizada'},409,page)
            closed=await self.checked(f'/transport/trips/{winner}/close',{'version':2,'reason':'Cierre de cancelado','warnings':[{'code':'Pendiente comunicado','evidence':{'source':'secretaria'}}]},200)
            self.assertIsNone(closed['officially_completed_at']);self.assertEqual(cancelled['cancelled_at'],closed['cancelled_at'])
            self.assertEqual(1,self.command('snapshot',{'trip_id':winner})['drivers'])
            await self.checked(f'/transport/trips/{winner}/assignments/release',{'resource_kind':'driver','reason':'Liberación explícita'})
            self.assertEqual(0,self.command('snapshot',{'trip_id':winner})['drivers'])
            await self.checked(f'/transport/trips/{winner}/history',None,200)
            await self.checked(f'/transport/trips/{winner}/assignments',None,200)
        finally: await context.close()

